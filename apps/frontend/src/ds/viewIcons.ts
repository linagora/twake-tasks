/** The icon of a view: the one it chose, or the eye. */
export function viewIcon(name: string | null | undefined): IconComponent {
  return (name ? BY_NAME.get(name) : undefined) ?? Eye
}

const fold = (text: string): string =>
  text
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()

// An icon's name in words: CheckList is "check list".
const nameWords = (name: string): string =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1 $2')

/** The icon names whose words start with every word of `query`. */
export function searchIcons(query: string): string[] {
  const words = fold(query).split(/\s+/).filter(Boolean)
  return VIEW_ICONS.filter(name => {
    const own = fold(
      `${name} ${nameWords(name)} ${WORDS.get(name) ?? ''}`
    ).split(/\s+/)
    return words.every(word => own.some(each => each.startsWith(word)))
  })
}
